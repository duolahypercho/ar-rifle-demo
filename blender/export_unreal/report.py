"""Pass R4: unreal/review/proof_summary.txt from fbx_check.json and review/proof/*.json."""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import config

R = os.path.join(config.OUT, 'review')


def load(p):
    p = os.path.join(R, p)
    return json.load(open(p)) if os.path.exists(p) else None


def main():
    L = []
    chk = load('fbx_check.json') or {}
    L.append('R4 proof summary (generated by blender/export_unreal/report.py)\n')
    L.append('== FBX as written (plain reader, fbxread.py) ==')
    L.append('body | FBX ver | UnitScaleFactor | up | front | root bones | Armature bone | bones (= GLB + Gun, GunIn) | parents | height (file units) | sole z | verts | blend shapes | embedded textures | MB')
    for n, b in chk.get('bodies', {}).items():
        L.append(f"{n} | {b['version']} | {b['unitScaleFactor']} | {'XYZ'[b['upAxis']]}{'+' if b['upSign'] > 0 else '-'} | "
                 f"{'XYZ'[b['frontAxis']]}{'+' if b['frontSign'] > 0 else '-'} | {b['rootBones']} | {b['armatureBone']} | "
                 f"{b['limbNodes']} {b['bonesMatchGlb']} | {b['parentsMatchGlb']} | {b['heightUnits']:.3f} | {b['soleZ']:.4f} | "
                 f"{b['vertices']} | {b['blendShapes']} | {len(b['embedded'])} | {b['bytes'] / 1e6:.1f}")
    for key, res in chk.get('animations', {}).items():
        ok = [r for r in res.values() if not r.get('missing')]
        bad = [c for c, r in res.items() if r.get('missing') or r['frames'] != r['glbKeys'] or not r['bonesMatch']
               or not r['parentsMatch'] or r['rootBones'] != ['root'] or r['fps'] != 30 or r['unit'] != 1 or r['up'] != 2
               or r['armatureBone']]
        rt = [r['rootTravelErrCm'] for r in ok if 'rootTravelErrCm' in r]
        L.append(f"animations/{key}: {len(res)} files, {sum(r['bytes'] for r in ok) / 1e6:.1f} MB; frames = GLB keys, 30 fps, "
                 f"unit 1 (cm), Z up, one root bone `root`, bones and parents = skeleton: {len(ok) - len(bad)} / {len(res)} "
                 f"(failing: {bad}); root travel from the FBX's own curves vs notes `root` ({len(rt)} clips): worst "
                 f"{max(rt) if rt else 0:.5f} cm")
    for key, r in chk.get('retarget', {}).items():
        L.append(f"retarget/{key}_apose.fbx: unit {r['unitScaleFactor']}, roots {r['rootBones']}, bones {r['bonesMatch']}, "
                 f"parents {r['parentsMatch']}, take {r['takes']}")
    for g, r in chk.get('weapons', {}).items():
        L.append(f"weapons/{g}.fbx: unit {r['unitScaleFactor']}, bounds cm {r['boundsCm']}, models {len(r['models'])}, "
                 f"embedded textures {r['embedded']}, {r['bytes'] / 1e6:.1f} MB")
    L.append('\n== Round trip: FBX re-imported in a fresh Blender vs the GLB clip on the GLB body (numpy FK) ==')
    for key in config.PACKS:
        a = load(f'proof/anims-{key}.json')
        if not a:
            continue
        L.append(f'-- {key} --')
        L.append('clip | frames | FBX range | fps | worst pos mm (bone) | worst deg (bone) | Gun mm / deg | root vs notes mm / deg | root travel m')
        for c, r in a.items():
            rn = f"{r['rootErrMm']:.5f} / {r['rootErrDeg']:.5f}" if r['rootNotes'] else 'in place'
            L.append(f"{c} | {r['frames']} | {r['fbxFrameRange']} | {r['sceneFps']:g} | {r['worstPosMm']:.4f} ({r['worstPosBone']}) | "
                     f"{r['worstDeg']:.4f} ({r['worstDegBone']}) | {r['gunPosMm']:.4f} / {r['gunDeg']:.4f} | {rn} | {r['rootTravelM']:.3f}")
    L.append('\n== Bodies re-imported (rest, morphs, skin under the animation FBX) ==')
    L.append('body | objects | bones | names / parents = GLB+2 | rest joint mm / deg | rest vertex mm | height m | morphs | morph mm | images')
    skin = []
    for n in config.BODIES:
        b = load(f'proof/body-{n}.json')
        if not b:
            continue
        L.append(f"{n} | {len(b['objects'])} {[o[1] for o in b['objects']]} | {b['bones']} | {b['boneNamesEqual']} / {b['parentsEqual']} | "
                 f"{b['restPosMm']:.4f} / {b['restDeg']:.4f} | {b['restVertexMm']:.4f} | {b['heightM']:.4f} | {len(b['shapeKeys'])} | "
                 f"{b.get('morphTargetMm', 0):.4f} | {len(b['images'])}")
        for clip, rows in b['skin'].items():
            for r in rows:
                skin.append(f"{n} | {clip} | {r['frame']} | {r['worstVertexMm']:.4f} | {r['meanVertexMm']:.5f}")
    L.append('\nbody | clip | frame | worst vertex mm | mean vertex mm   (body FBX posed by the animation FBX, vs the GLB body skinned by the GLB clip)')
    L += skin
    with open(os.path.join(R, 'proof_summary.txt'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
